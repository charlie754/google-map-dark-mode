#!/usr/bin/env node
/**
 * Embed the current GOAT Cam banner into the Firefox build.
 *
 *     node tools/embed-banner.mjs            # download, verify, write
 *
 * Why: Firefox/AMO treats the online banner download (goatcam.dagoat.io) as data
 * transmission that needs the user's explicit data-collection consent. Rather than
 * ask, the Firefox build ships the banner inside the package and never fetches it.
 * Chrome keeps downloading it online. Updating the Firefox banner therefore means
 * running this script and shipping a new Firefox release.
 *
 * The script downloads exactly what the Chrome runner downloads (banner/v1.signed
 * and the webp photo it names), verifies them with the same lib/banner-core.js
 * code and public key, and writes extension/lib/banner-embedded.js. The raw signed
 * file is kept in the output so test/checks/banner-embedded.test.mjs can re-verify
 * the signature and photo hash offline.
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { webcrypto, createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LIB = path.join(ROOT, "extension", "lib");
const OUT = path.join(LIB, "banner-embedded.js");
const ORIGIN = "https://goatcam.dagoat.io";

export function loadCore() {
  const context = vm.createContext({ crypto: webcrypto, TextEncoder, TextDecoder, Uint8Array, DataView, console, atob, btoa });
  for (const file of ["banner-core.js", "banner-key.js"]) {
    vm.runInContext(fs.readFileSync(path.join(LIB, file), "utf8"), context, { filename: file });
  }
  return { core: context.GoatBannerCore, key: context.GoatBannerKey };
}

const hexBytes = (hex) => Uint8Array.from(hex.match(/../g), (h) => Number.parseInt(h, 16));

export async function verify(signed, webp, nowMs) {
  const { core, key } = loadCore();
  const result = await core.evaluate(signed, {
    publicKeyRaw: hexBytes(key.publicKeyHex), nowMs, hwm: 0, floor: key.floor, storedBytes: null,
  });
  if (!result || result.action !== "show" || !result.banner) {
    throw new Error(`signed banner rejected: ${result && (result.reason || result.action)}`);
  }
  const photo = result.banner.photo;
  const checked = await core.checkPhoto(webp, { kind: "webp", sha256: photo.sha256.webp, w: photo.w, h: photo.h });
  if (!checked || checked.ok !== true) throw new Error(`photo rejected: ${checked && checked.reason}`);
  return result;
}

async function get(url) {
  const response = await fetch(url, { cache: "no-store", redirect: "error" });
  if (response.status !== 200) throw new Error(`${url}: HTTP ${response.status}`);
  return new Uint8Array(await response.arrayBuffer());
}

async function main() {
  const signed = await get(`${ORIGIN}/banner/v1.signed`);
  const { core, key } = loadCore();
  const pre = await core.evaluate(signed, {
    publicKeyRaw: hexBytes(key.publicKeyHex), nowMs: Date.now(), hwm: 0, floor: key.floor, storedBytes: null,
  });
  if (!pre || pre.action !== "show") throw new Error(`signed banner rejected: ${pre && (pre.reason || pre.action)}`);
  const webp = await get(`${ORIGIN}/banner/${pre.banner.photo.webp}`);
  const result = await verify(signed, webp, Date.now());
  const b64 = (bytes) => Buffer.from(bytes).toString("base64");
  const embedded = {
    source: `${ORIGIN}/banner/v1.signed`,
    embeddedAt: new Date().toISOString().slice(0, 10),
    revision: result.revision,
    signedSha256: result.sha256,
    webpSha256: createHash("sha256").update(webp).digest("hex"),
    signed: b64(signed),
    banner: result.banner,
    webp: b64(webp),
  };
  const body = `// GENERATED by tools/embed-banner.mjs on ${embedded.embeddedAt} -- do not edit by hand.
// Firefox build only (see manifest.firefox.json content_scripts). The GOAT Cam banner
// Chrome downloads from goatcam.dagoat.io, embedded so Firefox never makes that request.
// To update it: node tools/embed-banner.mjs, then ship a new Firefox release.
(function () {
  "use strict";
  const value = ${JSON.stringify(embedded, null, 2).replace(/\n/g, "\n  ")};
  globalThis.GoatBannerEmbedded = Object.freeze(value);
})();
`;
  fs.writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(ROOT, OUT)}: revision ${result.revision}, signed ${result.sha256.slice(0, 12)}, webp ${webp.length} bytes, expires ${result.banner.expires}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(error); process.exit(1); });
}
